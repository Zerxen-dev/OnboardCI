package reporter

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/Zerxen-dev/onboardci/internal/runner"
)

// GitHubPRReporter formats results as a GitHub PR markdown comment.
type GitHubPRReporter struct {
	BaseDir string
}

func NewGitHubPRReporter(baseDir string) *GitHubPRReporter {
	return &GitHubPRReporter{BaseDir: baseDir}
}

func (r *GitHubPRReporter) Format(report *runner.ExecutionReport) (string, error) {
	var sb strings.Builder

	sb.WriteString("## OnboardCI Onboarding Check Report\n\n")

	if report.Success {
		sb.WriteString("### :white_check_mark: All Documentation Steps Passed\n\n")
		sb.WriteString(fmt.Sprintf("A new contributor can successfully set up this project by following your documented steps (%d commands executed in clean container).\n\n", report.TotalCommands))
	} else {
		sb.WriteString("### :x: First-Time Contributor Blocked\n\n")
		if report.FailedStep != nil {
			failed := report.FailedStep
			relFile := failed.SourceFile
			if r.BaseDir != "" {
				if rel, err := filepath.Rel(r.BaseDir, failed.SourceFile); err == nil && !strings.HasPrefix(rel, "..") {
					relFile = rel
				}
			}

			sb.WriteString(fmt.Sprintf("**Failure Location**: `%s` (line %d)\n", relFile, failed.LineNumber))
			sb.WriteString(fmt.Sprintf("**Failed Command**: `%s`\n", failed.Command))
			sb.WriteString(fmt.Sprintf("**Diagnosis**: %s\n", failed.FailureReason))
			sb.WriteString(fmt.Sprintf("**Actionable Suggestion**: %s\n\n", failed.Suggestion))

			if failed.Stderr != "" {
				sb.WriteString("<details><summary>Captured Terminal Error</summary>\n\n```text\n")
				sb.WriteString(failed.Stderr)
				sb.WriteString("\n```\n</details>\n\n")
			}
		}
	}

	sb.WriteString("| # | Step Type | Command | Status |\n")
	sb.WriteString("|---|-----------|---------|--------|\n")
	for i, step := range report.Steps {
		status := ":white_check_mark: pass"
		if step.ExitCode != 0 {
			status = ":x: fail"
		}
		sb.WriteString(fmt.Sprintf("| %d | `%s` | `%s` | %s |\n", i+1, step.StepType, step.Command, status))
	}

	sb.WriteString("\n---\n*Report generated by [OnboardCI](https://github.com/Zerxen-dev/onboardci)*\n")
	return sb.String(), nil
}
